function useProductForm(
  initialData?: Partial<ProductFormData> & { id?: string },
  isInCampaign?: boolean
) {
  const isEditing = Boolean(initialData?.id)
  const [formData, setFormData] = useState<ProductFormData>(() => ({
    code: initialData?.code ?? '',
    name: initialData?.name ?? '',
    description: initialData?.description ?? '',
    unit: initialData?.unit ?? 'EA',
    category: initialData?.category ?? '',
    default_price: initialData?.default_price ?? 0,
    image_url: initialData?.image_url ?? '',
    is_active: initialData?.is_active ?? true,
    price_from: initialData?.price_from ?? null,
    price_includes_vat: initialData?.price_includes_vat ?? false,
    length_mm: initialData?.length_mm ?? null,
    width_mm: initialData?.width_mm ?? null,
    height_mm: initialData?.height_mm ?? null,
    thickness_mm: initialData?.thickness_mm ?? null,
    coverage_m2_per_unit: initialData?.coverage_m2_per_unit ?? null,
    coverage_linear_m_per_unit: initialData?.coverage_linear_m_per_unit ?? null,
    unit_weight_kg: initialData?.unit_weight_kg ?? null,
    pack_size: initialData?.pack_size ?? null,
    wastage_pct: initialData?.wastage_pct != null ? Number(initialData.wastage_pct) : 5,
    calculator_type: initialData?.calculator_type ?? '',
    sale_price: initialData?.sale_price ?? null,
    sale_starts_at: initialData?.sale_starts_at ?? null,
    sale_ends_at: initialData?.sale_ends_at ?? null,
    sale_label: initialData?.sale_label ?? null,
    track_stock: initialData?.track_stock ?? false,
    stock_quantity: initialData?.stock_quantity ?? 0,
    reorder_level: initialData?.reorder_level ?? 0,
    auto_generate_code: initialData?.auto_generate_code ?? !isEditing,
    variant_options: initialData?.variant_options ?? null,
    materials: initialData?.materials ?? null,
    family_slug: initialData?.family_slug ?? '',
    search_tags: initialData?.search_tags ?? null,
  }))
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [autoGenerateCode, setAutoGenerateCode] = useState(!isEditing)
  const [visibilityDialog, setVisibilityDialog] = useState<'clear-sale' | 'campaign-block' | null>(null)
  const [pendingVisibilityMode, setPendingVisibilityMode] = useState<'from' | 'quote' | null>(null)
  // Tracks the last code we auto-generated from a category change so we can
  // safely overwrite it if the user changes category again before editing it.
  const [autoGeneratedCode, setAutoGeneratedCode] = useState<string | null>(null)
  // The user's explicitly chosen price-visibility mode. Tracked separately
  // from the underlying price values so we can freely switch modes without
  // losing data (e.g. going quote → show keeps the trade price intact).
  const [priceVisibilityMode, setPriceVisibilityMode] = useState<
    'show' | 'from' | 'quote'
  >(() => {
    const dp = initialData?.default_price ?? 0
    const pf = initialData?.price_from ?? 0
    if (pf > 0) return 'from'
    if (dp > 0) return 'show'
    return 'quote'
  })

  function handleChange<T extends keyof ProductFormData>(field: T, value: ProductFormData[T]) {
    setFormData((prev) => ({ ...prev, [field]: value }))
  }

  async function generateCodeFromCategory(value: string) {
    if (!value.trim()) return
    const result = await generateProductCode(value)
    if (result.error || !result.code) return
    handleChange('code', result.code)
    setAutoGeneratedCode(result.code)
  }

  async function handleCategoryChange(value: string) {
    handleChange('category', value)

    // Auto-generate when the toggle is on. For new products this is the default.
    // For existing products the user must explicitly enable auto-generation.
    if (!autoGenerateCode || !value.trim()) return

    await generateCodeFromCategory(value)
  }

  function handleToggleAutoGenerate(next: boolean) {
    setAutoGenerateCode(next)
    handleChange('auto_generate_code', next)

    if (next && formData.category && (!formData.code || formData.code === autoGeneratedCode)) {
      generateCodeFromCategory(formData.category)
    }
  }

  function applyVisibilityModeRaw(mode: 'from' | 'quote') {
    if (mode === 'from') {
      // Default price_from to the current trade price when empty.
      handleChange('price_from', formData.price_from ?? formData.default_price ?? null)
    }
    // 'quote' intentionally keeps form values intact. We only zero them out
    // at submit time (see submit()), so the user can switch back without
    // re-typing. This is what fixes "stuck on quote".
  }

  function confirmClearSaleAndApplyMode() {
    handleChange('sale_price', null)
    handleChange('sale_starts_at', null)
    handleChange('sale_ends_at', null)
    handleChange('sale_label', null)
    if (pendingVisibilityMode) {
      applyVisibilityModeRaw(pendingVisibilityMode)
      setPriceVisibilityMode(pendingVisibilityMode)
    }
    setVisibilityDialog(null)
    setPendingVisibilityMode(null)
  }

  function cancelVisibilityDialog() {
    setVisibilityDialog(null)
    setPendingVisibilityMode(null)
  }

  function applyVisibilityMode(mode: 'show' | 'from' | 'quote') {
    // Going TO 'show' is always allowed: just clears 'from' and reveals the
    // trade price field. Even when the product is currently in quote mode we
    // let users switch back without re-prompting (sale was already cleared
    // when they went into quote).
    if (mode === 'show') {
      handleChange('price_from', null)
      setPriceVisibilityMode('show')
      return
    }

    // Switching away from Show price to 'from' or 'quote' disables discounts.
    // If the product has an active/scheduled individual sale, ask before
    // clearing it. If it's in a campaign, block the change entirely — campaigns
    // must be edited separately.
    if (formData.sale_price != null) {
      setPendingVisibilityMode(mode)
      setVisibilityDialog('clear-sale')
      return
    }

    if (isInCampaign) {
      setVisibilityDialog('campaign-block')
      return
    }

    applyVisibilityModeRaw(mode)
    setPriceVisibilityMode(mode)
  }

  async function submit() {
    setLoading(true)
    setError(null)

    // In 'quote' mode the public page must see no prices, so zero them out at
    // the boundary. Form state keeps the user's typed values so a later
    // mode switch doesn't lose data.
    const payload: ProductFormData = {
      ...formData,
      auto_generate_code: autoGenerateCode,
      default_price:
        priceVisibilityMode === 'quote' ? 0 : formData.default_price ?? 0,
      price_from:
        priceVisibilityMode === 'quote' ? null : formData.price_from,
    }

    const result = isEditing
      ? await updateProductRecord(initialData!.id!, payload)
      : await createProductRecord(payload)

    setLoading(false)

    if (result.error) {
      setError(result.error)
      return false
    }

    return true
  }

  return {
    isEditing,
    formData,
    loading,
    error,
    autoGenerateCode,
    handleChange,
    handleCategoryChange,
    handleToggleAutoGenerate,
    applyVisibilityMode,
    submit,
    visibilityDialog,
    cancelVisibilityDialog,
    confirmClearSaleAndApplyMode,
    priceVisibilityMode,
  }
}

