/**
 * Pull every option `text` out of a variant_options JSONB in the
 * order they were declared. Used to compute the canonical
 * search_tags set the form auto-bakes when the operator edits
 * variants, so a typed size ("UB 127x76x13kg") matches the
 * consolidated product via the search RPC without us having to
 * teach the RPC about the variant_options JSON shape.
 */
function extractVariantLabels(
  variantOptions: unknown
): string[] {
  if (!Array.isArray(variantOptions)) return []
  const out: string[] = []
  for (const v of variantOptions) {
    if (!v || typeof v !== 'object') continue
    const options = (v as { options?: unknown }).options
    if (!Array.isArray(options)) continue
    for (const o of options) {
      if (!o || typeof o !== 'object') continue
      const text = (o as { text?: unknown }).text
      if (typeof text === 'string' && text.trim()) out.push(text)
    }
  }
  return out
}

/**
 * Merge the variant option labels into the existing search_tags array
 * without dropping manually-entered tags. De-duplicates on output so
 * the search index stays compact. Returns null when both inputs are
 * empty so we don't write `[]` to the DB unnecessarily.
 */
function mergeSearchTags(
  existing: string[] | null | undefined,
  sizeLabels: string[]
): string[] | null {
  const set = new Set<string>()
  for (const tag of existing ?? []) {
    if (typeof tag === 'string' && tag.trim()) set.add(tag.trim())
  }
  for (const label of sizeLabels) {
    if (label && label.trim()) set.add(label.trim())
  }
  return set.size > 0 ? Array.from(set) : null
}

