// lib/location-images.ts
// Cinematic golden-hour location hero images for the /locations/[town]
// pages. Replaces the old 4-yard-photo pool that cycled across 935 pages.
//
// Mapping strategy — three-tier fallback:
//   1. Explicit town override     — ~90 main towns get a hand-picked image
//   2. County pool                — each county has 4-6 curated images
//   3. General-purpose pool       — 50 generic English countryside + arch
//                                   imagery used as the catch-all for
//                                   towns with no override or county match
//
// Tier 2/3 selections use a stable slug-hash so:
//   - the same town always gets the same image (no flicker on refresh)
//   - neighbouring towns share an image family, so the network feels
//     cohesive rather than random
//
// Total: 60 place-specific + 50 general-purpose = 110 unique images
// across ~935 towns. Main towns get a perfect hand-picked match; every
// other town falls through to the same wide generic pool (50 ≈ enough
// variety for each image to serve ~18 pages on average).
//
// General-purpose images are generated by
// `scripts/generate-general-purpose-location-images.mjs` against
// `scripts/location-general-purpose-prompts.json`. They're generic on
// purpose — no place-specific landmark or named landscape — so they can
// be reused for any of the ~845 minor delivery towns without a visual
// "mismatch" (e.g. a random Bedfordshire town shouldn't show Canterbury
// Cathedral). The 60 place-specific images stay reserved for the towns
// that genuinely deserve them (in TOWN_OVERRIDES) or for curated county
// pools (in COUNTY_POOL).

import { readdirSync } from 'node:fs'
import { join } from 'node:path'

export type ImageCategory = 'town' | 'landmark' | 'scenery' | 'character'

/**
 * Slugs that have a rendered WebP on disk. Built once at module load.
 * Used as a safety net so partial rollouts of the general-purpose pool
 * don't 404 — if a town hash-picks a slug whose file hasn't landed yet,
 * we fall through to the hero fallback instead.
 */
const READY_SLUGS: ReadonlySet<string> = (() => {
  try {
    const dir = join(process.cwd(), 'public', 'locations')
    return new Set(
      readdirSync(dir)
        .filter((f) => f.endsWith('.webp'))
        .map((f) => f.slice(0, -'.webp'.length)),
    )
  } catch {
    // public/locations doesn't exist in some build setups — empty set
    // is fine, the LOCATION_IMAGES registry still functions.
    return new Set()
  }
})()


