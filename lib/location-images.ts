/** Final fallback if every tier is empty. Should never trigger in practice. */
const FALLBACK_PATH = '/hero-1-4kgen.webp'

/**
 * Deterministic djb2 hash → stable index. Same slug always returns the
 * same image; flipping entries in a pool only reshuffles the mapping
 * for newly-affected slugs.
 */
function pickStable<T>(seed: string, pool: readonly T[]): T {
  if (pool.length === 0) {
    throw new Error('location-images: empty pool')
  }
  let h = 5381
  for (let i = 0; i < seed.length; i++) {
    h = ((h << 5) + h + seed.charCodeAt(i)) | 0
  }
  return pool[Math.abs(h) % pool.length]
}

/**
 * Resolve the hero image for a /locations/[town] page.
 *
 * @returns the WebP path + locality-aware alt text. Alt always references
 * the actual town so Google Images can rank each page for its area.
 */
export function getLocationImage(
  townSlug: string,
  // `_hub` retained for API compat with call sites; the new tier-3
  // general-purpose pool is region-agnostic, so the hub is no longer
  // used to choose an image.
  _hub: string,
  county: string,
  town: string,
): { path: string; alt: string } {
  const fallback = {
    path: FALLBACK_PATH,
    alt: `Building materials and aggregates being delivered to ${town}, ${county}`,
  }

  let imageSlug: string | undefined

  // Tier 1 — explicit town override
  imageSlug = TOWN_OVERRIDES[townSlug]

  // Tier 2 — county pool, picked by slug hash
  if (!imageSlug) {
    const countyImages = COUNTY_POOL[county]
    if (countyImages && countyImages.length > 0) {
      imageSlug = pickStable(townSlug, countyImages)
    }
  }

  // Tier 3 — general-purpose pool, picked by slug hash across the 50
  // generic images so every tier-3 town deterministically gets the
  // same image on every render.
  if (!imageSlug) {
    imageSlug = pickStable(townSlug, GENERAL_POOL)
  }

  if (!imageSlug) return fallback

  const img = IMAGE_BY_SLUG.get(imageSlug)
  if (!img) return fallback

  // Safety net: if the picked slug's WebP hasn't been generated yet
  // (partial rollout of the general-purpose pool), fall through to the
  // hero fallback instead of returning a path that would 404.
  if (!READY_SLUGS.has(imageSlug)) return fallback

  return {
    path: img.path,
    alt: `${img.baseAlt}, near ${town}, ${county}`,
  }
} 